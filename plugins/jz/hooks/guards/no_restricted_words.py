"""Deny a commit message, pull request body, review or comment that carries text the house keeps out of public posts.

An emoji, a dingbat, an attribution trailer, a session link, a model version
slug, or a word the repository lists under a "Restricted words" heading in
AGENTS.md or CLAUDE.md. Each of those reached a public post at least once
before this guard existed. A body file is read in the command's directory,
and the restricted-word list is the union of the instruction files from that
directory up to the root of its repository.
"""

import json
import os
import re

from command_lines import git_call
from gh_options import gh_command
from git_push import git_text
from guards import Deny, read_text

NAME = "no-restricted-words"

EMOJI = re.compile("[\U0001F300-\U0001FAFF☀-➿️]")
ATTRIBUTION = re.compile(r"(?im)^\s*(co-authored-by|generated[- ]with|generated by)\b.*\b(claude|anthropic|codex|openai|gpt|copilot)")
SESSION_LINK = re.compile(r"claude\.ai/code/|claude://|chatgpt\.com/codex/")
MODEL_SLUG = re.compile(r"(?i)\b(claude-(opus|sonnet|haiku|fable)-\d|gpt-\d|o\d-(mini|pro)\b)")

# git commit short options. Those in COMMIT_VALUE_LETTERS take the rest of the
# cluster, or the next token, as their value.
COMMIT_VALUE_LETTERS = "mFCct"
COMMIT_PROSE_LETTERS = "mF"
JSON_PROSE_KEYS = {"body", "title", "message", "text", "commit_title", "commit_message"}

def read_file(path, directory):
    """The text of a body or instruction file, or "" when there is nothing to judge: stdin, a missing path, a device, a FIFO."""
    if path == "-":
        return ""
    full = path if os.path.isabs(path) else os.path.join(directory, path)
    found = read_text(full)
    return found[0] if found else ""


def json_prose(text):
    """The prose fields of a JSON request body, or the raw text when it is not JSON."""
    try:
        document = json.loads(text)
    except ValueError:
        return [text]
    found = []

    def walk(node):
        if isinstance(node, dict):
            for key, value in node.items():
                if key in JSON_PROSE_KEYS and isinstance(value, str):
                    found.append(value)
                else:
                    walk(value)
        elif isinstance(node, list):
            for item in node:
                walk(item)

    walk(document)
    return found


def value_after(tokens, i):
    return tokens[i + 1] if i + 1 < len(tokens) else ""


def commit_texts(args, directory):
    """Message and trailer text of a git commit, clusters such as -am included."""
    i = 0
    while i < len(args):
        token = args[i]
        if token in {"--message", "--file", "--trailer"}:
            value = value_after(args, i)
            yield read_file(value, directory) if token == "--file" else value
            i += 2
            continue
        if token.startswith("--message=") or token.startswith("--trailer="):
            yield token.split("=", 1)[1]
        elif token.startswith("--file="):
            yield read_file(token.split("=", 1)[1], directory)
        elif token.startswith("-") and not token.startswith("--") and len(token) > 1:
            for position, letter in enumerate(token[1:], start=1):
                if letter in COMMIT_VALUE_LETTERS:
                    attached = token[position + 1:]
                    value = attached if attached else value_after(args, i)
                    if not attached:
                        i += 1
                    if letter in COMMIT_PROSE_LETTERS:
                        yield read_file(value, directory) if letter == "F" else value
                    break
        i += 1


def gh_texts(rest, directory):
    for i, t in enumerate(rest):
        if t in {"-b", "--body", "-t", "--title"}:
            yield value_after(rest, i)
        elif t.startswith("--body=") or t.startswith("--title="):
            yield t.split("=", 1)[1]
        elif t in {"-F", "--body-file"} and rest[0] != "api":
            yield read_file(value_after(rest, i), directory)
        elif t.startswith("--body-file="):
            yield read_file(t.split("=", 1)[1], directory)
        elif t == "--input":
            for text in json_prose(read_file(value_after(rest, i), directory)):
                yield text
        elif t in {"-f", "-F", "--field", "--raw-field"} and rest[0] == "api":
            field = value_after(rest, i)
            if "=" in field:
                key, val = field.split("=", 1)
                if key in {"body", "title", "message"}:
                    yield read_file(val[1:], directory) if val.startswith("@") else val


def texts_from(argv, directory):
    """Yield (text, directory) for every piece of prose the call would publish."""
    name = os.path.basename(argv[0])
    if name == "git":
        call = git_call(argv, directory)
        if call is not None and call[0] == "commit":
            _, args, git_directory = call
            for text in commit_texts(args, git_directory):
                yield text, git_directory
    else:
        gh = gh_command(argv)
        if gh is not None and gh[0][:1] and gh[0][0] in {"pr", "issue", "api"}:
            for text in gh_texts(list(gh[0]) + gh[1], directory):
                yield text, directory


def repository_root(directory):
    return git_text(directory, [], ["rev-parse", "--show-toplevel"]) or None


def policy_directories(directory):
    """The command's directory and its ancestors up to the root of its repository.

    A nested repository is a boundary of its own, and a directory outside any
    repository answers only to its own instruction files.
    """
    here = os.path.realpath(directory)
    root = repository_root(here)
    if root is None or not (here == root or here.startswith(root + os.sep)):
        return [here]
    chain = []
    while True:
        chain.append(here)
        if here == root:
            return chain
        here = os.path.dirname(here)


def words_listed_in(text):
    match = re.search(r"(?ims)^#+\s*restricted words\s*$\n(.*?)(?=^#|\Z)", text)
    if not match:
        return []
    words_found = []
    for line in match.group(1).splitlines():
        line = line.strip().lstrip("-*").strip().strip("\x60")
        if line and " " not in line:
            words_found.append(line)
    return words_found


def restricted_words(directory, policies_by_directory):
    if directory in policies_by_directory:
        return policies_by_directory[directory]
    words_found = []
    for policy_directory in policy_directories(directory):
        for name in ("AGENTS.md", "CLAUDE.md"):
            for word in words_listed_in(read_file(name, policy_directory)):
                if word not in words_found:
                    words_found.append(word)
    policies_by_directory[directory] = words_found
    return words_found


def findings(text, restricted):
    out = []
    if EMOJI.search(text):
        out.append("an emoji or dingbat")
    if ATTRIBUTION.search(text):
        out.append("an attribution trailer naming an agent")
    if SESSION_LINK.search(text):
        out.append("an agent session link")
    if MODEL_SLUG.search(text):
        out.append("a model version slug")
    for word in restricted:
        if re.search(r"(?i)\b" + re.escape(word) + r"\b", text):
            out.append("the restricted word " + word)
    return out


def check(context):
    policies_by_directory = {}
    for argv, directory in context.calls:
        for text, policy_directory in texts_from(argv, directory):
            if not text:
                continue
            found = findings(text, restricted_words(policy_directory, policies_by_directory))
            if found:
                return Deny("Blocked: the text to be published contains " + ", ".join(found) + ".",
                            "Rewrite it in plain words, then rerun.")
    return None
